'use strict';
// Validates data/api-catalogue.json itself, so a hand-edited entry cannot silently break the
// api-discovery skill or leave an API without its trust label, CORS result or verdict.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { ROOT, SKILLS_DIR, skillNames } = require('./helpers');

const catalogue = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'api-catalogue.json'), 'utf8'));
const TRUST = ['trusted', 'untrusted', 'trusted-host-untrusted-content'];
const CORS = ['pass', 'pass-for-simple-GET', 'fail', 'untested'];

test('catalogue has a date and a non-empty list', () => {
  assert.match(catalogue.updated, /^\d{4}-\d{2}-\d{2}$/);
  assert.ok(Array.isArray(catalogue.apis) && catalogue.apis.length > 0);
});

test('ids are unique, lower-case kebab-case', () => {
  const ids = catalogue.apis.map((a) => a.id);
  assert.equal(new Set(ids).size, ids.length, 'duplicate id');
  for (const id of ids) assert.match(id, /^[a-z0-9]+(-[a-z0-9]+)*$/, id);
});

for (const a of catalogue.apis) {
  test(`${a.id}: required fields, trust label, CORS result and verdict`, () => {
    assert.ok(typeof a.name === 'string' && a.name.length > 0);
    assert.ok(Array.isArray(a.category) && a.category.length > 0 && a.category.every((c) => typeof c === 'string'));
    assert.match(a.docs, /^https:\/\//, 'docs must be an https link');
    assert.ok(['none', 'key', 'oauth'].includes(a.auth), `auth: ${a.auth}`);
    assert.equal(typeof a.https, 'boolean');
    assert.ok(TRUST.includes(a.trust), `trust: ${a.trust}`);
    assert.ok(typeof a.verdict === 'string' && a.verdict.length > 0);
    assert.ok(a.cors && CORS.includes(a.cors.result), `cors.result: ${a.cors && a.cors.result}`);
    assert.match(a.cors.tested, /^\d{4}-\d{2}-\d{2}$/, 'every CORS result carries its test date');
    assert.ok(typeof a.cors.method === 'string' && a.cors.method.length > 0);
    assert.ok(Array.isArray(a.usedBy));
  });
}

test('an API a skill uses is trusted-host and verified suitable', () => {
  const skills = new Set(skillNames());
  for (const a of catalogue.apis) {
    for (const s of a.usedBy) {
      // usedBy names a skill that exists (github-status, weather, ...) once it has been built
      assert.ok(skills.has(s) || ['weather', 'currency', 'news', 'github-status'].includes(s), `${a.id}: unknown skill ${s}`);
    }
    if (a.usedBy.length > 0) {
      assert.ok(a.verdict.startsWith('yes'), `${a.id} is used by a skill but its verdict is ${a.verdict}`);
      assert.notEqual(a.trust, 'untrusted', `${a.id} is used by a skill but marked untrusted`);
      assert.equal(a.auth, 'none', `${a.id}: skills here are keyless`);
    }
  }
});

test('every skill that uses the network is backed by a catalogue entry', () => {
  const used = new Set(catalogue.apis.flatMap((a) => a.usedBy));
  for (const name of skillNames()) {
    const meta = JSON.parse(fs.readFileSync(path.join(ROOT, 'src', 'skills', name, 'skill.meta.json'), 'utf8'));
    if (meta.network !== 'none') assert.ok(used.has(name), `${name} uses the network but no catalogue entry lists it in usedBy`);
  }
  assert.ok(fs.existsSync(SKILLS_DIR));
});

test('docs/API-CATALOGUE.md is generated from the data and lists every entry', () => {
  const doc = fs.readFileSync(path.join(ROOT, 'docs', 'API-CATALOGUE.md'), 'utf8');
  assert.match(doc, /^<!-- Generated by scripts\/build\.js/m);
  assert.ok(doc.includes(`last updated ${catalogue.updated}`), 'stale: run npm run build');
  for (const a of catalogue.apis) {
    assert.ok(doc.includes(`- id: \`${a.id}\``), `${a.id} missing from docs/API-CATALOGUE.md`);
    assert.ok(doc.includes(`## ${a.name}`), `${a.name} heading missing`);
  }
});

test('the data embedded in api-discovery matches data/api-catalogue.json', () => {
  const html = fs.readFileSync(path.join(SKILLS_DIR, 'api-discovery', 'scripts', 'index.html'), 'utf8');
  const m = /^const API_CATALOGUE = (.*);$/m.exec(html);
  assert.ok(m, 'embedded catalogue not found; run npm run build');
  assert.deepEqual(JSON.parse(m[1]), catalogue, 'built skill is stale: run npm run build');
  assert.doesNotMatch(m[1], /</, '"<" must be escaped so the data cannot close the script element');
});
