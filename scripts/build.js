#!/usr/bin/env node
// Builds src/skills/<name>/ into skills/<name>/ (what the app loads) and regenerates CATALOG.md.
// Each skill is fetched independently by the app, so shared code is inlined, not imported.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'skills');
const INLINE = /^\/\/ @inline (\S+)\s*$/;

// `// @inline-json data/file.json NAME` embeds a repo JSON file as `const NAME = {...};`, because a
// skill is loaded on its own and cannot read the repo at runtime. "<" is escaped so the data can
// never close the surrounding <script> element.
const INLINE_JSON = /^\/\/ @inline-json (\S+) (\w+)\s*$/;

function embedJson(relPath, name) {
  const file = path.join(ROOT, relPath);
  if (!fs.existsSync(file)) throw new Error(`cannot embed '${relPath}' (not found)`);
  const data = JSON.stringify(JSON.parse(fs.readFileSync(file, 'utf8')))
    .replace(/</g, '\\u003c')
    .replace(new RegExp(String.fromCharCode(0x2028), 'g'), '\\u2028')
    .replace(new RegExp(String.fromCharCode(0x2029), 'g'), '\\u2029');
  return `const ${name} = ${data};`;
}

function inlineSource(file, seen = new Set()) {
  return fs.readFileSync(file, 'utf8').split(/\r?\n/).map((line) => {
    const j = INLINE_JSON.exec(line);
    if (j) return embedJson(j[1], j[2]);
    const m = INLINE.exec(line);
    if (!m) return line;
    const target = path.join(SRC, m[1]);
    if (!fs.existsSync(target)) throw new Error(`${file}: cannot inline '${m[1]}' (not found)`);
    if (seen.has(target)) return '';
    seen.add(target);
    return `// ---- inlined from src/${m[1]} ----\n` + inlineSource(target, seen);
  }).join('\n');
}

function buildSkill(name) {
  const dir = path.join(SRC, 'skills', name);
  const dest = path.join(OUT, name);
  fs.rmSync(dest, { recursive: true, force: true });
  fs.mkdirSync(path.join(dest, 'scripts'), { recursive: true });

  // __REPO_URL__ lets a skill identify this project to a provider (e.g. Wikimedia's
  // Api-User-Agent); it comes from site.config.json so there is one place to edit.
  const site = JSON.parse(fs.readFileSync(path.join(ROOT, 'site.config.json'), 'utf8'));
  const js = inlineSource(path.join(dir, 'main.js')).replace(/__REPO_URL__/g, site.repoUrl);
  if (/<\/script/i.test(js)) throw new Error(`${name}: source contains '</script', would break the page`);
  const html = `<!DOCTYPE html>\n<html lang="en">\n<head><meta charset="UTF-8"></head>\n<body>\n<script>\n${js}\n</script>\n</body>\n</html>\n`;
  fs.writeFileSync(path.join(dest, 'scripts', 'index.html'), html);

  for (const f of ['SKILL.md', 'README.md']) {
    fs.copyFileSync(path.join(dir, f), path.join(dest, f));
  }
  if (fs.existsSync(path.join(dir, 'assets'))) {
    fs.cpSync(path.join(dir, 'assets'), path.join(dest, 'assets'), { recursive: true });
  }
  return JSON.parse(fs.readFileSync(path.join(dir, 'skill.meta.json'), 'utf8'));
}

function descriptionOf(name) {
  const md = fs.readFileSync(path.join(SRC, 'skills', name, 'SKILL.md'), 'utf8');
  const m = /^description:\s*(.+)$/m.exec(md);
  return m ? m[1].trim() : '';
}

function writeCatalog(rows) {
  const site = JSON.parse(fs.readFileSync(path.join(ROOT, 'site.config.json'), 'utf8'));
  const lines = [
    '# Skill catalogue',
    '',
    '<!-- Generated by scripts/build.js. Do not edit by hand. -->',
    '',
    `Load URL base: \`${site.pagesBase}\` (edit \`site.config.json\` once you know your GitHub username).`,
    'In the app: Agent Skills > Skills > (+) > Load skill from URL > paste the load URL (the skill folder, no `SKILL.md` on the end).',
    '',
    '| Skill | Type | Network | Secret | Status | Load URL |',
    '|---|---|---|---|---|---|',
    ...rows.map((r) =>
      `| ${r.name} | ${r.type} | ${r.network} | ${r.secret} | ${r.status} | \`${site.pagesBase}/skills/${r.name}\` |`),
    '',
  ];
  fs.writeFileSync(path.join(ROOT, 'CATALOG.md'), lines.join('\n'));
}

// docs/API-CATALOGUE.md is generated from data/api-catalogue.json so the two can never drift.
function writeApiDoc() {
  const cat = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'api-catalogue.json'), 'utf8'));
  const cell = (v) => String(v === undefined || v === null || v === '' ? '-' : v)
    .replace(/\|/g, '/').replace(/\s+/g, ' ');
  const corsText = (a) => (a.cors ? `${a.cors.result} (${a.cors.tested})` : '-');
  const lines = [
    '# API catalogue',
    '',
    '<!-- Generated by scripts/build.js from data/api-catalogue.json. Do not edit by hand. -->',
    '',
    `Curated results only, last updated ${cat.updated}. Every CORS result carries the date and method of the test. ` +
      'Candidates were taken from the providers\' own documentation; the public API lists named in the brief are discovery sources only, never trusted providers. ' +
      'Rejected candidates and the reasons are in `research/rejected-apis.md`; the full scorecards are in `research/api-candidates.md`. ' +
      'The `api-discovery` skill searches this same data on the phone.',
    '',
    '**Trust labels:** `trusted` = official provider, checked against its own documentation. ' +
      '`trusted-host-untrusted-content` = official host, but it returns text written by others (always treated as data). ' +
      '`untrusted` = catalogue listing only.',
    '',
    '| API | Category | Verdict | Trust | CORS (tested) | Used by |',
    '|---|---|---|---|---|---|',
  ];
  cat.apis.forEach((a) => {
    lines.push(`| ${cell(a.name)} | ${cell((a.category || []).join(', '))} | ${cell(a.verdict)} | ${cell(a.trust)} | ${cell(corsText(a))} | ${cell((a.usedBy || []).join(', ') || 'no skill yet')} |`);
  });
  lines.push('');
  cat.apis.forEach((a) => {
    lines.push(`## ${cell(a.name)}`, '');
    lines.push(`- id: \`${a.id}\``);
    ['docs', 'terms', 'endpoint', 'limits', 'commercial', 'attribution', 'privacy', 'freshness'].forEach((k) => {
      if (a[k]) lines.push(`- ${k}: ${cell(a[k])}`);
    });
    lines.push(`- key needed: ${a.auth}; HTTPS: ${a.https ? 'yes' : 'no'}`);
    if (a.cors) lines.push(`- CORS: ${cell(a.cors.result)}, tested ${cell(a.cors.tested)}, method: ${cell(a.cors.method)}`);
    lines.push(`- trust: ${a.trust}; verdict: ${a.verdict}`, '');
  });
  fs.writeFileSync(path.join(ROOT, 'docs', 'API-CATALOGUE.md'), lines.join('\n'));
}

function main() {
  const names = fs.readdirSync(path.join(SRC, 'skills'), { withFileTypes: true })
    .filter((d) => d.isDirectory()).map((d) => d.name).sort();
  const rows = names.map((name) => ({ name, ...buildSkill(name) }));
  writeCatalog(rows);
  writeApiDoc();
  console.log(`Built ${names.length} skill(s): ${names.join(', ')}`);
}

main();
